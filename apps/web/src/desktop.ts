/**
 * Открыто ли приложение внутри десктопной обёртки (Tauri).
 *
 * Десктоп не вшивает свою копию интерфейса, а открывает сайт с сервера —
 * так он обновляется вместе с каждой выкладкой. Значит, это обычная
 * веб-сборка, и узнать «я в программе» можно только во время работы: Tauri
 * подкладывает в окно свой мост __TAURI_INTERNALS__. MODE === 'desktop'
 * оставлен для локальной сборки через build:desktop.
 */
export const IS_DESKTOP =
  import.meta.env.MODE === 'desktop' ||
  (typeof window !== 'undefined' && '__TAURI_INTERNALS__' in window);
